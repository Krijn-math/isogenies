#!/usr/bin/env python3
"""Generate the short links /thesis/<slug> for every doctor in data/graph.json.

Run from anywhere:  python3 tools/build_links.py
Each doctor gets a redirect page thesis_data/<slug>.html that sends the visitor
to their thesis PDF (or, without a PDF, to their entry in the forest). The short
URL /thesis/<slug> reaches it through the site's root 404.html, which forwards
/thesis/<slug> to /thesis/thesis_data/<slug>.html.
Slugs follow the same rule as the page: lowercase first name, and 2, 3, ... for
later namesakes in order of defence year. A "slug" field on a person in
graph.json overrides the rule. Pages this script created earlier but no longer
needs are removed; it never touches a file without its marker line.
"""
import html, json, re, shutil, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINKS = ROOT / "thesis_data"
MARKER = "<!-- generated by tools/build_links.py -->"
OLD_MARKER = ".shortlink"   # earlier versions made a folder <slug>/ per doctor
# names already used in thesis/ and thesis/thesis_data/
RESERVED = {"assets", "data", "tools", "index", "index.html", "404", "thesis_data", "eprint", "graph", "src"}


def base_slug(name):
    first = name.strip().split()[0] if name.strip() else ""
    first = unicodedata.normalize("NFD", first)
    first = "".join(c for c in first if not unicodedata.combining(c)).lower()
    return re.sub(r"[^a-z0-9]", "", first) or "doctor"


def assign_slugs(nodes):
    taken = set(RESERVED) | {n["slug"] for n in nodes if n.get("slug")}
    eligible = [n for n in nodes if not n.get("slug") and not n.get("external")]
    eligible.sort(key=lambda n: (n.get("year") or 9999, n["name"]))
    for n in eligible:
        b = base_slug(n["name"]); s, k = b, 2
        while s in taken:
            s, k = f"{b}{k}", k + 1
        n["slug"] = s; taken.add(s)


PAGE = MARKER + """
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title}</title>
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url={url}">
<link rel="canonical" href="{url}">
<script>location.replace({url_js});</script>
</head>
<body style="font-family:Georgia,serif;padding:2em">
<p>Redirecting to <a href="{url}">{what}</a>&hellip;</p>
</body>
</html>
"""


def main():
    data = json.loads((ROOT / "data" / "graph.json").read_text(encoding="utf-8"))
    nodes = data.get("nodes", [])
    assign_slugs(nodes)
    wanted = {}
    for n in nodes:
        slug = n.get("slug")
        if not slug:
            continue
        if not re.fullmatch(r"[a-z0-9-]+", slug) or slug in RESERVED:
            sys.exit(f"Bad slug {slug!r} for {n['name']}")
        pdf = n.get("pdf") or ""
        if re.match(r"https?://", pdf):
            url, what = pdf, f"the thesis of Dr. {n['name']}"
        else:
            url, what = f"../#{slug}", f"Dr. {n['name']} in the Isogeny Forest"
        wanted[slug] = (url, what, n["name"])

    LINKS.mkdir(exist_ok=True)
    ours = lambda f: f.is_file() and f.read_text(encoding="utf-8").startswith(MARKER)
    # remove stale pages created by this script, and folders from the old layout
    for f in LINKS.iterdir():
        if f.is_dir() and (f / OLD_MARKER).exists():
            shutil.rmtree(f)
            print("removed old folder", f.name + "/")
        elif f.suffix == ".html" and ours(f) and f.stem not in wanted:
            f.unlink()
            print("removed", f.name)

    for slug, (url, what, name) in sorted(wanted.items()):
        f = LINKS / f"{slug}.html"
        if f.exists() and not ours(f):
            sys.exit(f"{f.name} exists and was not made by this script; set a different slug.")
        f.write_text(PAGE.format(
            title=html.escape(f"Dr. {name}"), url=html.escape(url, quote=True),
            url_js=json.dumps(url).replace("</", "<\\/"), what=html.escape(what)), encoding="utf-8")
        print(f"{slug:>14}  ->  {url}")


if __name__ == "__main__":
    main()
