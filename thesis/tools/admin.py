#!/usr/bin/env python3
"""A local editor for The Isogeny Forest.

    python3 thesis/tools/admin.py [--root DIR] [--port N] [--no-browser]

Starts a small web page on http://127.0.0.1:8770 (or the next free port) for editing
people and who supervised whom. Every edit is written to thesis_data/graph/overrides.json,
which thesis_data/graph/to_graph.py applies on top of theses.json; after each save the
server runs to_graph.py and tools/build_links.py and shows what they printed. Nothing is
committed: review the changes (the page has a "Changes" tab) and commit them yourself.

The Inbox keeps pasted "Add a doctor" / "Fix a mistake" emails in tools/admin-inbox.json.
--root (or the environment variable FOREST_ROOT) points at another copy of the thesis/
folder, for example a scratch copy to try things out on. Standard library only.
"""
import argparse, ast, copy, datetime, http.server, importlib.util, json, os, re, secrets
import shutil, subprocess, sys, tempfile, threading, unicodedata, webbrowser
from pathlib import Path
from urllib.parse import urlparse

FIELDS = ["name", "year", "university", "country", "title", "pdf", "homepage",
          "slug", "short", "label", "external", "phd"]
MARK = "<!-- Everything below is regenerated by to_graph.py. -->"


def fold(s):
    """Same as in to_graph.py: accents off, lowercase, words."""
    s = unicodedata.normalize("NFD", s); s = "".join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"[^a-z ]", "", s.lower().replace("-", " ")).split()


def ext_id(name):
    return "x-" + "-".join(fold(name))


def surname_id(name):
    n = re.sub(r",?\s+Jr\.?$", "", name.strip())
    last = n.split()[-1] if n.split() else ""
    last = unicodedata.normalize("NFD", last)
    last = "".join(c for c in last if not unicodedata.combining(c)).lower()
    return re.sub(r"[^a-z0-9-]", "", last).strip("-") or "doctor"


def today():
    return datetime.date.today().isoformat()


class Forest:
    """Reads and writes the data files of one thesis/ folder."""

    def __init__(self, root):
        self.root = root
        self.overrides = root / "thesis_data" / "graph" / "overrides.json"
        self.to_graph = root / "thesis_data" / "graph" / "to_graph.py"
        self.tocheck = root / "thesis_data" / "graph" / "TO-CHECK.md"
        self.theses = root / "thesis_data" / "theses.json"
        self.graph_path = root / "data" / "graph.json"
        self.build_links = root / "tools" / "build_links.py"
        self.inbox_path = root / "tools" / "admin-inbox.json"
        self.flags = root / "assets" / "vendor" / "flags"
        self.lock = threading.RLock()
        self._base = self._base_key = None
        self._links = self._links_key = None
        self.last_run = None

    # ---------- reading ----------
    def load_ov(self):
        if not self.overrides.exists():
            return {}
        return json.loads(self.overrides.read_text(encoding="utf-8"))

    def ov_text(self):
        return self.overrides.read_text(encoding="utf-8") if self.overrides.exists() else None

    def write_ov(self, ov):
        self._write(self.overrides, json.dumps(ov, ensure_ascii=False, indent=1) + "\n")

    @staticmethod
    def _write(path, text):
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, path)

    def graph(self):
        if not self.graph_path.exists():
            return {"meta": {}, "nodes": [], "edges": []}
        return json.loads(self.graph_path.read_text(encoding="utf-8"))

    def rename(self):
        """The RENAME map of to_graph.py (old id -> id on the page), if it has one."""
        m = re.search(r"^RENAME\s*=\s*(\{[^}]*\})", self.to_graph.read_text(encoding="utf-8"), re.M)
        try:
            return ast.literal_eval(m.group(1)) if m else {}
        except (ValueError, SyntaxError):
            return {}

    def theses_ids(self, ren):
        T = json.loads(self.theses.read_text(encoding="utf-8")).get("theses", [])
        return {ren.get(r["id"], r["id"]) for r in T}

    def base(self):
        """graph.json as to_graph.py builds it from theses.json alone (no overrides), cached."""
        key = tuple((p.stat().st_mtime_ns, p.stat().st_size) for p in (self.theses, self.to_graph))
        if self._base_key != key:
            with tempfile.TemporaryDirectory(prefix="forest-base-") as d:
                d = Path(d)
                (d / "thesis_data" / "graph").mkdir(parents=True)
                (d / "data").mkdir()
                shutil.copy(self.to_graph, d / "thesis_data" / "graph" / "to_graph.py")
                shutil.copy(self.theses, d / "thesis_data" / "theses.json")
                p = subprocess.run([sys.executable, "thesis_data/graph/to_graph.py"], cwd=d,
                                   capture_output=True, text=True, timeout=300)
                if p.returncode:
                    raise RuntimeError("to_graph.py fails even without overrides:\n" + p.stdout + p.stderr)
                g = json.loads((d / "data" / "graph.json").read_text(encoding="utf-8"))
            self._base = {"nodes": {n["id"]: n for n in g["nodes"]},
                          "edges": {(e["from"], e["to"]) for e in g["edges"]}}
            self._base_key = key
        return self._base

    def links(self):
        """tools/build_links.py as a module (for its slug rule)."""
        key = self.build_links.stat().st_mtime_ns
        if self._links_key != key:
            sys.dont_write_bytecode = True   # no __pycache__ in the repository
            spec = importlib.util.spec_from_file_location("forest_build_links", self.build_links)
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            self._links, self._links_key = m, key
        return self._links

    def slugs(self, nodes):
        """id -> short-link slug each person gets (explicit or by the default rule)."""
        tmp = copy.deepcopy(nodes)
        self.links().assign_slugs(tmp)
        return {n["id"]: n.get("slug") for n in tmp}

    def inbox(self):
        if not self.inbox_path.exists():
            return {"items": []}
        return json.loads(self.inbox_path.read_text(encoding="utf-8"))

    def state(self):
        g, ov, ren = self.graph(), self.load_ov(), self.rename()
        rid = lambda i: ren.get(i, i)
        b, tids = self.base(), self.theses_ids(ren)
        slugs = self.slugs(g["nodes"])
        patches = {rid(k): v for k, v in ov.get("nodes", {}).items()}
        people = []
        for n in g["nodes"]:
            p = dict(n)
            p["_slug"] = slugs.get(n["id"])
            p["_origin"] = ("theses" if n["id"] in tids else "supervisor" if n["id"] in b["nodes"] else "overrides")
            p["_patch"] = patches.get(n["id"])
            people.append(p)
        dropped = []
        for i in ov.get("drop", []):
            i = rid(i)
            dropped.append({"id": i, "name": (b["nodes"].get(i) or {}).get("name", i)})
        stale = (self.overrides.exists() and self.graph_path.exists()
                 and self.overrides.stat().st_mtime > self.graph_path.stat().st_mtime + 1)
        return {"root": str(self.root), "people": people,
                "edges": [[e["from"], e["to"]] for e in g["edges"]],
                "updated": g.get("meta", {}).get("updated"), "dropped": dropped,
                "reserved": sorted(self.links().RESERVED), "stale": stale,
                "last_run": self.last_run, "inbox": self.inbox().get("items", []),
                "tocheck": self.tocheck.read_text(encoding="utf-8") if self.tocheck.exists() else ""}

    # ---------- validation ----------
    def clean(self, raw):
        """Form strings -> values as stored (None = empty). Only keys that were sent."""
        f, err = {}, {}
        for k in FIELDS:
            if k not in raw:
                continue
            v = raw[k]
            if k == "external":
                f[k] = True if v else None
                continue
            v = "" if v is None else str(v).strip()
            if k in ("year", "phd"):
                if not v:
                    f[k] = None
                elif re.fullmatch(r"\d{4}", v):
                    f[k] = int(v)
                else:
                    err[k] = "A year is four digits, e.g. 2024."
            elif k == "country":
                f[k] = v.lower() or None
            else:
                f[k] = re.sub(r"\s+", " ", v) or None
        return f, err

    def validate(self, f, pid, nodes, new):
        err = {}
        name = f.get("name")
        if (new or "name" in f) and not name:
            err["name"] = "A name is needed."
        ext = f.get("external") if "external" in f else next((n.get("external") for n in nodes if n["id"] == pid), None)
        if not ext and "year" in f and f["year"] is None:
            err["year"] = "Doctors need the year of their defence."
        for k in ("pdf", "homepage"):
            if f.get(k) and not re.fullmatch(r"https?://\S+", f[k]):
                err[k] = "A link starts with http:// or https:// and has no spaces."
        if f.get("country") and not re.fullmatch(r"[a-z]{2}", f["country"]):
            err["country"] = "Two letters, e.g. nl."
        s = f.get("slug")
        if s:
            if not re.fullmatch(r"[a-z0-9-]+", s):
                err["slug"] = "Only a-z, 0-9 and -."
            elif s in self.links().RESERVED:
                err["slug"] = "This name is reserved."
            else:
                for i, t in self.slugs(nodes).items():
                    if t == s and i != pid:
                        who = next(n["name"] for n in nodes if n["id"] == i)
                        err["slug"] = f"Already the short link of {who}."
        return err

    # ---------- override edits ----------
    @staticmethod
    def _patch(ov, pid, f, cur, b, tids, rid):
        """Write the fields that differ from the current graph as a patch of person pid."""
        nodes = ov.setdefault("nodes", {})
        key = next((k for k in nodes if rid(k) == pid), pid)
        patch = nodes.get(key, {})
        bn = b["nodes"].get(pid)
        for k, v in f.items():
            if cur.get(k) == v:
                continue
            if bn is not None:
                if bn.get(k) == v:
                    patch.pop(k, None)
                elif v is None:
                    patch[k] = None
                else:
                    patch[k] = v
            elif v is None:
                if pid in tids:
                    patch[k] = None
                else:
                    patch.pop(k, None)
            else:
                patch[k] = v
        if patch:
            nodes[key] = patch
        else:
            nodes.pop(key, None)

    @staticmethod
    def _add_edge(ov, b, rid, a, t):
        same = lambda e: rid(e[0]) == a and rid(e[1]) == t
        if "remove_edges" in ov:
            ov["remove_edges"] = [e for e in ov["remove_edges"] if not same(e)]
        if (a, t) not in b["edges"] and not any(same(e) for e in ov.get("add_edges", [])):
            ov.setdefault("add_edges", []).append([a, t])

    @staticmethod
    def _remove_edge(ov, b, rid, a, t):
        same = lambda e: rid(e[0]) == a and rid(e[1]) == t
        if "add_edges" in ov:
            ov["add_edges"] = [e for e in ov["add_edges"] if not same(e)]
        if (a, t) in b["edges"] and not any(same(e) for e in ov.get("remove_edges", [])):
            ov.setdefault("remove_edges", []).append([a, t])

    @staticmethod
    def _tidy(ov, ids, b, tids, rid):
        """Forget outside supervisors made in overrides.json who, after this edit, supervise nobody
        (to_graph.py would leave them out anyway)."""
        linked = {rid(i) for e in ov.get("add_edges", []) for i in e[:2]}
        for k in [k for k in ov.get("nodes", {}) if rid(k) in ids]:
            n = ov["nodes"][k]
            if n.get("external") and rid(k) not in b["nodes"] and rid(k) not in tids and rid(k) not in linked:
                del ov["nodes"][k]

    def save_person(self, req):
        with self.lock:
            ov, g, ren = self.load_ov(), self.graph(), self.rename()
            rid = lambda i: ren.get(i, i)
            b, tids = self.base(), self.theses_ids(ren)
            gn = {n["id"]: n for n in g["nodes"]}
            pid = req.get("id") or None
            new = pid is None
            if pid and pid not in gn:
                return {"ok": False, "errors": {"_": f"Unknown person {pid}. Reload the page."}}
            f, err = self.clean(req.get("fields") or {})
            err.update({k: v for k, v in self.validate(f, pid, g["nodes"], new).items() if k not in err})
            byname = {" ".join(fold(n["name"])): n["id"] for n in g["nodes"]}
            sup_ids, new_ext = [], {}
            for s in req.get("supervisors") or []:
                if s.get("id"):
                    if s["id"] in gn: sup_ids.append(s["id"])
                    else: err["supervisors"] = f"Unknown person {s['id']}."
                elif (s.get("name") or "").strip():
                    nm = re.sub(r"\s+", " ", s["name"].strip())
                    hit = byname.get(" ".join(fold(nm)))
                    if hit:
                        sup_ids.append(hit)
                    elif not fold(nm):
                        err["supervisors"] = f"{nm!r} is not a usable name."
                    else:
                        xid, k = ext_id(nm), 2
                        while xid in gn:   # that id belongs to someone who was renamed since
                            xid, k = f"{ext_id(nm)}-{k}", k + 1
                        new_ext[xid] = nm; sup_ids.append(xid)
            stu_ids = []
            for s in req.get("students") or []:
                if s.get("id") in gn: stu_ids.append(s["id"])
                else: err["students"] = "Students must already be in the forest; add them first."
            if pid and (pid in sup_ids or pid in stu_ids):
                err["supervisors"] = "Nobody supervises themselves."
            if set(sup_ids) & set(stu_ids):
                err["students"] = "Someone is both a supervisor and a student."
            if err:
                return {"ok": False, "errors": err}

            old_text = self.ov_text()
            nodes = ov.setdefault("nodes", {})
            if new:
                taken = (set(gn) | set(b["nodes"]) | {rid(k) for k in nodes} | {rid(i) for i in ov.get("drop", [])}
                         | tids | set(ren) | set(ren.values()))
                stem = ext_id(f["name"]) if f.get("external") else surname_id(f["name"])
                pid, k = stem, 2
                while pid in taken:
                    pid, k = f"{stem}-{k}", k + 1
                nodes[pid] = {k2: f[k2] for k2 in FIELDS if f.get(k2) is not None}
                cur_sup, cur_stu = set(), set()
            else:
                self._patch(ov, pid, f, gn[pid], b, tids, rid)
                cur_sup = {a for a, t in ((e["from"], e["to"]) for e in g["edges"]) if t == pid}
                cur_stu = {t for a, t in ((e["from"], e["to"]) for e in g["edges"]) if a == pid}
            for xid, nm in new_ext.items():
                if "drop" in ov:
                    ov["drop"] = [i for i in ov["drop"] if rid(i) != xid]
                if xid not in b["nodes"]:
                    key = next((k for k in nodes if rid(k) == xid), xid)
                    e = nodes.setdefault(key, {})
                    nodes[key] = {"name": nm, "external": True, **{k: v for k, v in e.items() if k not in ("name", "external")}}
            for a in sup_ids:
                if a not in cur_sup: self._add_edge(ov, b, rid, a, pid)
            for a in cur_sup - set(sup_ids):
                self._remove_edge(ov, b, rid, a, pid)
            for t in stu_ids:
                if t not in cur_stu: self._add_edge(ov, b, rid, pid, t)
            for t in cur_stu - set(stu_ids):
                self._remove_edge(ov, b, rid, pid, t)
            self._tidy(ov, (cur_sup - set(sup_ids)) | (cur_stu - set(stu_ids)), b, tids, rid)
            self.write_ov(ov)
            run = self.rebuild(old_text)
            return {"ok": run["ok"], "id": pid, "run": run,
                    "errors": {} if run["ok"] else {"_": "The build failed, so the change was undone. See the output."}}

    def delete(self, pid):
        with self.lock:
            ov, g, ren = self.load_ov(), self.graph(), self.rename()
            rid = lambda i: ren.get(i, i)
            b, tids = self.base(), self.theses_ids(ren)
            if pid not in {n["id"] for n in g["nodes"]}:
                return {"ok": False, "errors": {"_": f"Unknown person {pid}."}}
            old_text = self.ov_text()
            if pid in b["nodes"] or pid in tids:
                # from theses.json: "drop" them; their patches and added links stay in the file
                # (to_graph.py ignores them while dropped), so "bring back" restores everything
                if pid not in {rid(i) for i in ov.get("drop", [])}:
                    ov.setdefault("drop", []).append(pid)
            else:
                # made in overrides.json: remove the entry and its links
                near = {e["from"] for e in g["edges"] if e["to"] == pid}
                for k in [k for k in ov.get("nodes", {}) if rid(k) == pid]:
                    del ov["nodes"][k]
                if "add_edges" in ov:
                    ov["add_edges"] = [e for e in ov["add_edges"] if pid not in (rid(e[0]), rid(e[1]))]
                self._tidy(ov, near, b, tids, rid)
            self.write_ov(ov)
            run = self.rebuild(old_text)
            return {"ok": run["ok"], "run": run}

    def restore(self, pid):
        with self.lock:
            ov, ren = self.load_ov(), self.rename()
            old_text = self.ov_text()
            ov["drop"] = [i for i in ov.get("drop", []) if ren.get(i, i) != pid]
            self.write_ov(ov)
            run = self.rebuild(old_text)
            return {"ok": run["ok"], "run": run}

    # ---------- build ----------
    def _run_scripts(self):
        steps = []
        for script in ("thesis_data/graph/to_graph.py", "tools/build_links.py"):
            try:
                p = subprocess.run([sys.executable, script], cwd=self.root, capture_output=True, text=True, timeout=300)
                steps.append({"cmd": "python3 " + script, "code": p.returncode, "out": p.stdout, "err": p.stderr})
            except Exception as e:  # noqa: BLE001
                steps.append({"cmd": "python3 " + script, "code": -1, "out": "", "err": str(e)})
            if steps[-1]["code"]:
                break
        return steps

    def rebuild(self, old_text=None):
        """Run to_graph.py and build_links.py; if one fails, put overrides.json back as it was."""
        with self.lock:
            steps = self._run_scripts()
            ok = all(s["code"] == 0 for s in steps)
            run = {"ok": ok, "steps": steps, "time": datetime.datetime.now().strftime("%H:%M:%S")}
            if not ok and old_text is not None:
                self._write(self.overrides, old_text)
                run["rolled_back"] = True
                run["rollback_ok"] = all(s["code"] == 0 for s in self._run_scripts())
            self.last_run = run
            return run

    # ---------- changes since the last commit ----------
    def _git(self, *args):
        return subprocess.run(["git", *args], cwd=self.root, capture_output=True, text=True, timeout=60)

    def changes(self):
        try:
            top = self._git("rev-parse", "--show-toplevel")
        except FileNotFoundError:
            return {"git": False, "message": "git is not installed."}
        if top.returncode:
            return {"git": False, "message": f"{self.root} is not inside a git repository."}
        old = self._git("show", "HEAD:./thesis_data/graph/overrides.json")
        old_ov = json.loads(old.stdout) if old.returncode == 0 and old.stdout.strip() else {}
        new_ov = self.load_ov()
        names = {}
        for src in (old_ov.get("nodes", {}), new_ov.get("nodes", {})):
            for i, p in src.items():
                if isinstance(p, dict) and p.get("name"): names[i] = p["name"]
        try:
            names.update({i: n.get("name", i) for i, n in self.base()["nodes"].items()})
        except RuntimeError:
            pass
        names.update({n["id"]: n.get("name", n["id"]) for n in self.graph()["nodes"]})
        return {"git": True,
                "stat": self._git("diff", "--stat", "HEAD", "--", ".").stdout,
                "status": self._git("status", "--short", "--untracked-files=all", "--", ".").stdout,
                "diff": self._git("diff", "HEAD", "--", "thesis_data/graph/overrides.json").stdout,
                "summary": summarize(old_ov, new_ov, lambda i: names.get(i, i))}

    # ---------- inbox ----------
    def inbox_op(self, req):
        with self.lock:
            box = self.inbox()
            items = box.setdefault("items", [])
            act = req.get("action")
            if act == "add":
                text = (req.get("text") or "").strip()
                if not text:
                    return {"ok": False, "error": "Nothing pasted."}
                item = {"id": secrets.token_hex(4), "added": today(), "kind": req.get("kind") or "note",
                        "done": False, "text": text}
                items.insert(0, item)
            elif act in ("update", "delete"):
                item = next((x for x in items if x.get("id") == req.get("id")), None)
                if not item:
                    return {"ok": False, "error": "No such inbox item."}
                if act == "delete":
                    items.remove(item)
                else:
                    for k in ("done", "kind", "created", "about"):
                        if k in req: item[k] = req[k]
            else:
                return {"ok": False, "error": "Unknown inbox action."}
            self._write(self.inbox_path, json.dumps(box, ensure_ascii=False, indent=1) + "\n")
            return {"ok": True, "items": items}


def summarize(old, new, name):
    """A readable list of what changed between two versions of overrides.json."""
    out = []
    fmt = lambda v: "(cleared)" if v is None else json.dumps(v, ensure_ascii=False)
    on, nn = old.get("nodes", {}), new.get("nodes", {})
    for i in nn:
        a, c = on.get(i), nn[i]
        if a == c:
            continue
        if a is None:
            what = "Added " if c.get("name") and not i.startswith("x-") else "Added outside supervisor " if c.get("name") else "Changed "
            out.append(what + name(i) + ": " + "; ".join(f"{k} {fmt(v)}" for k, v in c.items()))
        else:
            ch = [f"{k}: {fmt(a[k]) if k in a else '(as in theses.json)'} → {fmt(c[k]) if k in c else '(as in theses.json)'}"
                  for k in dict.fromkeys([*a, *c]) if a.get(k, ...) != c.get(k, ...)]
            out.append(f"Changed {name(i)}: " + "; ".join(ch))
    for i in on:
        if i not in nn:
            out.append(f"Removed all overrides of {name(i)}")
    edge = lambda e: f"{name(e[0])} → {name(e[1])}"
    pairs = lambda d, k: {tuple(e[:2]) for e in d.get(k, [])}
    for e in sorted(pairs(new, "add_edges") - pairs(old, "add_edges")): out.append("New supervision link " + edge(e))
    for e in sorted(pairs(old, "add_edges") - pairs(new, "add_edges")): out.append("Dropped added link " + edge(e))
    for e in sorted(pairs(new, "remove_edges") - pairs(old, "remove_edges")): out.append("Removed supervision link " + edge(e))
    for e in sorted(pairs(old, "remove_edges") - pairs(new, "remove_edges")): out.append("Restored link " + edge(e))
    for i in new.get("drop", []):
        if i not in old.get("drop", []): out.append(f"Deleted {name(i)}")
    for i in old.get("drop", []):
        if i not in new.get("drop", []): out.append(f"Brought back {name(i)}")
    for k in dict.fromkeys([*old, *new]):
        if k not in ("nodes", "add_edges", "remove_edges", "drop") and old.get(k) != new.get(k):
            out.append(f"Edited {k}")
    return out


class Handler(http.server.BaseHTTPRequestHandler):
    forest = None
    token = ""
    port = 0
    server_version = "IsogenyForestAdmin"

    def log_message(self, fmt, *args):
        if args and str(args[1] if len(args) > 1 else "").startswith(("4", "5")):
            sys.stderr.write("%s\n" % (fmt % args))

    def _send(self, code, body, ctype="application/json; charset=utf-8"):
        if isinstance(body, (dict, list)):
            body = json.dumps(body, ensure_ascii=False)
        data = body.encode("utf-8") if isinstance(body, str) else body
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(data)

    def _allowed(self, api):
        # refuse requests made through another host name (DNS rebinding) and, for the API,
        # requests from other web pages (they cannot know the token in this page)
        if self.headers.get("Host") not in (f"127.0.0.1:{self.port}", f"localhost:{self.port}"):
            self._send(403, {"error": "forbidden host"}); return False
        if api and not secrets.compare_digest(self.headers.get("X-Forest-Token", ""), self.token):
            self._send(403, {"error": "bad token; reload the page"}); return False
        return True

    def do_GET(self):
        path = urlparse(self.path).path
        if not self._allowed(path.startswith("/api/")):
            return
        try:
            if path in ("/", "/index.html"):
                self._send(200, PAGE.replace("__TOKEN__", self.token), "text/html; charset=utf-8")
            elif re.fullmatch(r"/flags/[a-z0-9-]+\.svg", path):
                f = self.forest.flags / path.rsplit("/", 1)[1]
                if f.is_file(): self._send(200, f.read_bytes(), "image/svg+xml")
                else: self._send(404, {"error": "no flag"})
            elif path == "/api/state":
                self._send(200, self.forest.state())
            elif path == "/api/changes":
                self._send(200, self.forest.changes())
            else:
                self._send(404, {"error": "not found"})
        except Exception as e:  # noqa: BLE001
            self._send(500, {"ok": False, "error": f"{type(e).__name__}: {e}"})

    def do_POST(self):
        path = urlparse(self.path).path
        if not self._allowed(True):
            return
        try:
            n = int(self.headers.get("Content-Length") or 0)
            req = json.loads(self.rfile.read(n) or b"{}") if n else {}
            F = self.forest
            if path == "/api/person": res = F.save_person(req)
            elif path == "/api/delete": res = F.delete(req.get("id"))
            elif path == "/api/restore": res = F.restore(req.get("id"))
            elif path == "/api/rebuild": res = F.rebuild()
            elif path == "/api/inbox": res = F.inbox_op(req)
            else: return self._send(404, {"error": "not found"})
            self._send(200, res)
        except Exception as e:  # noqa: BLE001
            self._send(500, {"ok": False, "error": f"{type(e).__name__}: {e}"})


